-- Phase B（B1）：团队与跨团队订阅
--
-- 目标：
--  1. 新增组织级 team / team_member；
--  2. subscription.team（自由文本）→ team_id：同 org 内同名合并（忽略大小写与首尾空白）；
--  3. notification.team_id 回填：能匹配团队的填上，匹配不到的历史通知保留 NULL（仅供 org_admin 审计）。
--
-- 兼容策略（与阶段 A 的「先 NULL、写入路径补齐后再收紧」一致）：
--  - subscription.team / notification.team 保留为「名称快照」，B2 起写路径以 team_id 为准；
--  - V4 只建表 + 回填，team_id 暂允许 NULL，旧唯一键 (repo_id, method, path, team) 保留：
--    B1 可独立发布，旧代码写订阅不受影响；
--  - B2 写入路径上线后由 V5 收紧：回填过渡期新增的 NULL、同名合并去重、
--    唯一键切换为 (repo_id, method, path, team_id)、team_id SET NOT NULL、旧 team 列改可空。

-- ── 1. 团队 ────────────────────────────────────────────────────────────────
CREATE TABLE team (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id BIGINT NOT NULL REFERENCES org(id) ON DELETE RESTRICT,
    name VARCHAR(128) NOT NULL,
    description VARCHAR(1024) NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_team_org_name UNIQUE (org_id, name),
    CONSTRAINT chk_team_name CHECK (length(trim(name)) > 0)
);
CREATE INDEX idx_team_org ON team (org_id);

-- ── 2. 团队成员（lead / member）─────────────────────────────────────────────
CREATE TABLE team_member (
    team_id BIGINT NOT NULL REFERENCES team(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE RESTRICT,
    role VARCHAR(16) NOT NULL DEFAULT 'member',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (team_id, user_id),
    CONSTRAINT chk_team_member_role CHECK (role IN ('lead', 'member'))
);
CREATE INDEX idx_team_member_user ON team_member (user_id);

-- ── 3. 从旧订阅文本建团队：同 org 内按 lower(trim(name)) 合并 ───────────────
INSERT INTO team (org_id, name, description, created_at)
SELECT COALESCE(s.org_id, r.org_id) AS org_id,
       MIN(TRIM(s.team)) AS name,
       '',
       MIN(s.created_at)
FROM subscription s
LEFT JOIN repo r ON r.id = s.repo_id
WHERE COALESCE(s.org_id, r.org_id) IS NOT NULL
GROUP BY COALESCE(s.org_id, r.org_id), LOWER(TRIM(s.team));

-- ── 4. 回填 subscription.team_id ───────────────────────────────────────────
ALTER TABLE subscription ADD COLUMN team_id BIGINT;

UPDATE subscription s
SET team_id = t.id
FROM team t
WHERE t.org_id = COALESCE(s.org_id, (SELECT r.org_id FROM repo r WHERE r.id = s.repo_id))
  AND LOWER(t.name) = LOWER(TRIM(s.team));

-- ── 5. 回填 notification.team_id（匹配不到保留 NULL）───────────────────────
ALTER TABLE notification ADD COLUMN team_id BIGINT;

UPDATE notification n
SET team_id = t.id
FROM team t
WHERE t.org_id = COALESCE(n.org_id, (SELECT r.org_id FROM repo r WHERE r.id = n.repo_id))
  AND LOWER(t.name) = LOWER(TRIM(n.team));

-- ── 6. 旧数据成员回填：团队名 = 用户名（忽略大小写）且为同组织 active 成员 → lead
INSERT INTO team_member (team_id, user_id, role, created_at)
SELECT t.id, u.id, 'lead', now()
FROM team t
JOIN app_user u ON LOWER(u.username) = LOWER(t.name)
JOIN org_membership om
  ON om.user_id = u.id
 AND om.org_id = t.org_id
 AND om.status = 'active';

-- ── 7. 过渡期约束（B2 写入路径上线后由 V5 收紧）───────────────────────────
-- 本迁移保留旧唯一键 (repo_id, method, path, team) 与可空 team_id，
-- 避免 B1 合并后、B2 写入路径上线前旧代码写订阅失败。
-- V5 负责：回填过渡期新增的 NULL team_id、同名合并去重、切换唯一键、收紧 NOT NULL。
ALTER TABLE subscription ADD CONSTRAINT fk_subscription_team FOREIGN KEY (team_id) REFERENCES team(id) ON DELETE RESTRICT;
CREATE INDEX idx_subscription_org_team ON subscription (org_id, team_id);

ALTER TABLE notification ADD CONSTRAINT fk_notification_team FOREIGN KEY (team_id) REFERENCES team(id) ON DELETE SET NULL;
CREATE INDEX idx_notification_org_team ON notification (org_id, team_id, created_at);
