-- Phase 2 管理库 schema（PostgreSQL 18.x）
-- 时间统一 UTC（timestamptz）；布尔 BOOLEAN；大文本 TEXT。
-- 管理库内部外键默认 ON DELETE RESTRICT，删除由 Service 显式编排。

CREATE TABLE project (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(128) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_project_name UNIQUE (name)
);

CREATE TABLE repo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES project(id) ON DELETE RESTRICT,
    url TEXT NOT NULL,
    branch VARCHAR(128) NOT NULL DEFAULT 'main',
    sync_status VARCHAR(32) NOT NULL DEFAULT 'new',
    last_error TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_repo_project_url UNIQUE (project_id, url)
);
CREATE INDEX idx_repo_url ON repo (url);

CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(128) NOT NULL,
    display_name VARCHAR(128) NOT NULL DEFAULT '',
    token_hash VARCHAR(128) NOT NULL,
    is_platform_admin BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- 用户名不敏感唯一（§8.2）：PG 默认区分大小写，显式 lower() 表达式唯一索引
CREATE UNIQUE INDEX uk_app_user_username_lower ON app_user (lower(username));

CREATE TABLE membership (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE RESTRICT,
    -- project 数据迁入管理库后补 FK；当前 project 仍由投影层承载（逻辑引用）
    project_id BIGINT NOT NULL,
    role VARCHAR(32) NOT NULL,
    CONSTRAINT uk_membership_user_project UNIQUE (user_id, project_id)
);
CREATE INDEX idx_membership_project ON membership (project_id);

CREATE TABLE comment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id BIGINT NOT NULL REFERENCES repo(id) ON DELETE RESTRICT,
    api_id BIGINT,
    doc_id BIGINT,
    method VARCHAR(16) NOT NULL DEFAULT '',
    path TEXT NOT NULL DEFAULT '',
    author VARCHAR(128) NOT NULL,
    body TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_comment_repo ON comment (repo_id, created_at);
CREATE INDEX idx_comment_api ON comment (api_id, created_at);

CREATE TABLE subscription (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id BIGINT NOT NULL REFERENCES repo(id) ON DELETE RESTRICT,
    api_id BIGINT,
    method VARCHAR(16) NOT NULL,
    path TEXT NOT NULL,
    team VARCHAR(128) NOT NULL,
    notify_url TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_subscription_endpoint UNIQUE (repo_id, method, path, team)
);
CREATE INDEX idx_subscription_endpoint ON subscription (repo_id, method, path);

CREATE TABLE notification (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team VARCHAR(128) NOT NULL,
    repo_id BIGINT NOT NULL REFERENCES repo(id) ON DELETE RESTRICT,
    method VARCHAR(16) NOT NULL,
    path TEXT NOT NULL,
    summary TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_notification_team ON notification (team, created_at);

CREATE TABLE review (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id BIGINT NOT NULL REFERENCES repo(id) ON DELETE RESTRICT,
    path TEXT NOT NULL,
    new_content TEXT NOT NULL,
    diff TEXT NOT NULL DEFAULT '',
    old_hash VARCHAR(128),
    status VARCHAR(32) NOT NULL DEFAULT 'pending',
    requester VARCHAR(128) NOT NULL,
    reviewer VARCHAR(128),
    reject_reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolved_at TIMESTAMPTZ
);
CREATE INDEX idx_review_repo_status ON review (repo_id, status);

CREATE TABLE mock_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id BIGINT NOT NULL REFERENCES repo(id) ON DELETE RESTRICT,
    api_id BIGINT,
    field_pattern TEXT NOT NULL,
    rule_type VARCHAR(32) NOT NULL,
    rule_value TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_mock_rule_repo ON mock_rule (repo_id);

CREATE TABLE changelog (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id BIGINT REFERENCES repo(id) ON DELETE RESTRICT,
    api_id BIGINT,
    actor VARCHAR(128) NOT NULL,
    action VARCHAR(64) NOT NULL,
    detail TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_changelog_repo ON changelog (repo_id, created_at);
