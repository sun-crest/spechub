-- Phase 2：发布状态迁入管理库（release 标记无法从 git 重建）
-- 投影层 version.stage 改为重建时按本表重放的派生值。
CREATE TABLE release (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id BIGINT NOT NULL REFERENCES repo(id) ON DELETE RESTRICT,
    path VARCHAR(512) NOT NULL,
    spec_hash VARCHAR(128) NOT NULL,
    released_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_release_repo_path UNIQUE (repo_id, path)
);
CREATE INDEX idx_release_repo ON release (repo_id);
