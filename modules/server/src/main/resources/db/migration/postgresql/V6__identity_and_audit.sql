-- Phase C（C1）：身份与审计基础（PostgreSQL 18.x）
--
-- 兼容策略（与阶段 A/B 的两阶段迁移纪律一致）：
--  - V6 只加列 / 建表 / 回填：旧代码（app_user.token_hash + is_platform_admin）仍可启动与写入；
--  - C2–C4 代码切换到 user_token / org_membership 后，由 V7 删除旧列；
--  - 会话不落管理库：阶段 C 直接使用 Spring Session Data Redis，本迁移不建 user_session / SPRING_SESSION 表。

-- ── 1. app_user 身份列 ────────────────────────────────────────────────────
ALTER TABLE app_user ADD COLUMN email VARCHAR(255);
ALTER TABLE app_user ADD COLUMN password_hash VARCHAR(255);
ALTER TABLE app_user ADD COLUMN password_updated_at TIMESTAMPTZ;
ALTER TABLE app_user ADD COLUMN status VARCHAR(32) NOT NULL DEFAULT 'active';
ALTER TABLE app_user ADD COLUMN must_change_password BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE app_user ADD COLUMN mfa_enabled BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE app_user ADD COLUMN last_login_at TIMESTAMPTZ;

ALTER TABLE app_user ADD CONSTRAINT chk_app_user_status CHECK (status IN ('active', 'disabled', 'invited'));

-- 旧 token_hash 在 C2 停止写入后允许为空（新用户只走 user_token）；V7 再删列。
ALTER TABLE app_user ALTER COLUMN token_hash DROP NOT NULL;

-- 邮箱唯一、忽略大小写；允许 NULL（未绑定邮箱的旧用户 / OIDC-only 用户）。
-- Service 层写入前统一 trim().lowercase()，DB 索引兜底防重复。
CREATE UNIQUE INDEX uk_app_user_email_lower ON app_user (lower(email)) WHERE email IS NOT NULL;

-- ── 2. user_token（用户 API 令牌）──────────────────────────────────────────
-- 迁移前检查：token_hash 理论上不应重复；若有则中止并要求人工处理，
-- 避免 user_token.token_hash 唯一键静默丢凭据。
DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM app_user
        WHERE token_hash IS NOT NULL
        GROUP BY token_hash
        HAVING COUNT(*) > 1
    ) THEN
        RAISE EXCEPTION 'V6 中止：app_user.token_hash 存在重复值，需人工处理后再迁移';
    END IF;
END $$;

CREATE TABLE user_token (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    name VARCHAR(128) NOT NULL,
    token_prefix VARCHAR(32) NOT NULL DEFAULT '',
    token_hash VARCHAR(128) NOT NULL,
    purpose VARCHAR(32) NOT NULL,
    expires_at TIMESTAMPTZ,
    used_at TIMESTAMPTZ,
    last_used_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_user_token_hash UNIQUE (token_hash),
    CONSTRAINT chk_user_token_purpose CHECK (purpose IN ('legacy', 'api', 'invite', 'password_reset')),
    -- legacy 行来自旧 app_user.token_hash，无过期信息；其余用途必须有过期时间。
    CONSTRAINT chk_user_token_expiry CHECK (purpose = 'legacy' OR expires_at IS NOT NULL)
);
CREATE INDEX idx_user_token_user ON user_token (user_id, created_at);

-- 旧令牌继续有效（ADR §10）：逐行复制为 legacy，不设过期。
INSERT INTO user_token (user_id, name, token_prefix, token_hash, purpose, created_at)
SELECT id, 'legacy', '', token_hash, 'legacy', created_at
FROM app_user
WHERE token_hash IS NOT NULL;

-- ── 3. service_account（项目级服务账号）────────────────────────────────────
CREATE TABLE service_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id BIGINT NOT NULL REFERENCES org(id) ON DELETE RESTRICT,
    project_id BIGINT NOT NULL REFERENCES project(id) ON DELETE RESTRICT,
    name VARCHAR(128) NOT NULL,
    token_prefix VARCHAR(32) NOT NULL,
    token_hash VARCHAR(128) NOT NULL,
    role VARCHAR(16) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'active',
    expires_at TIMESTAMPTZ NOT NULL,
    last_used_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_service_account_token_hash UNIQUE (token_hash),
    CONSTRAINT chk_service_account_role CHECK (role IN ('viewer', 'editor')),
    CONSTRAINT chk_service_account_status CHECK (status IN ('active', 'revoked'))
);
CREATE INDEX idx_service_account_org ON service_account (org_id);
CREATE INDEX idx_service_account_project ON service_account (project_id);
-- 名称在项目内忽略大小写唯一；与项目成员可同名（不共享成员表）。
CREATE UNIQUE INDEX uk_service_account_project_name_lower ON service_account (project_id, lower(name));

-- ── 4. user_identity（OIDC 身份绑定）───────────────────────────────────────
CREATE TABLE user_identity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    -- provider = 'oidc:<issuer>'（或 registration id）；subject = OIDC sub。
    provider VARCHAR(255) NOT NULL,
    subject VARCHAR(255) NOT NULL,
    email VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_user_identity_provider_subject UNIQUE (provider, subject)
);
CREATE INDEX idx_user_identity_user ON user_identity (user_id);
CREATE INDEX idx_user_identity_email ON user_identity (email);

-- ── 5. audit_event（管理动作审计）──────────────────────────────────────────
-- org_id / actor_user_id 不建外键：审计需在用户 / 组织删除后保留；actor_name 存快照。
CREATE TABLE audit_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id BIGINT NOT NULL,
    actor_user_id BIGINT,
    actor_name VARCHAR(128) NOT NULL,
    actor_type VARCHAR(32) NOT NULL,
    action VARCHAR(64) NOT NULL,
    target_type VARCHAR(64),
    target_id VARCHAR(128),
    detail TEXT,
    outcome VARCHAR(16) NOT NULL,
    ip VARCHAR(64),
    user_agent VARCHAR(512),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT chk_audit_event_actor_type CHECK (actor_type IN ('user', 'service_account', 'anonymous')),
    CONSTRAINT chk_audit_event_outcome CHECK (outcome IN ('success', 'failure'))
);
CREATE INDEX idx_audit_event_org_created ON audit_event (org_id, created_at);
CREATE INDEX idx_audit_event_org_action_created ON audit_event (org_id, action, created_at);
CREATE INDEX idx_audit_event_actor_created ON audit_event (actor_user_id, created_at);
