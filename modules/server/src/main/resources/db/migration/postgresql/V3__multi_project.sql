-- Phase A：多项目骨架（单组织）
-- 过渡策略：org_id / slug / external_repo_id 等新列先允许 NULL，由 A2 写入路径补齐，
-- 后续迁移再收紧；本迁移只保证现有数据回填后仍可读、可写。
-- 阶段 A 不引入 email / password_hash / mfa_enabled（阶段 C）。

-- ── 1. 组织 ────────────────────────────────────────────────────────────────
CREATE TABLE org (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(128) NOT NULL,
    slug VARCHAR(64) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'active',
    plan VARCHAR(32),
    trial_ends_at TIMESTAMPTZ,
    quota_json TEXT,
    suspended_reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_org_slug UNIQUE (slug),
    CONSTRAINT chk_org_status CHECK (status IN ('pending_verification', 'active', 'suspended', 'archived', 'deleted'))
);

INSERT INTO org (name, slug, status) VALUES ('default', 'default', 'active');

-- ── 2. 组织成员关系（app_user 保持全局身份）────────────────────────────────
CREATE TABLE org_membership (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE RESTRICT,
    org_id BIGINT NOT NULL REFERENCES org(id) ON DELETE RESTRICT,
    org_role VARCHAR(32) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'active',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_org_membership_user_org UNIQUE (user_id, org_id),
    CONSTRAINT chk_org_membership_role CHECK (org_role IN ('org_admin', 'org_member')),
    CONSTRAINT chk_org_membership_status CHECK (status IN ('active', 'disabled', 'invited'))
);
CREATE INDEX idx_org_membership_org ON org_membership (org_id);

INSERT INTO org_membership (user_id, org_id, org_role, status)
SELECT u.id, o.id,
       CASE WHEN u.is_platform_admin THEN 'org_admin' ELSE 'org_member' END,
       'active'
FROM app_user u
CROSS JOIN (SELECT id FROM org WHERE slug = 'default') o;

-- ── 3. Git 连接（阶段 A 只建表；外部 provider 连接器留 D1）─────────────────
CREATE TABLE git_connection (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id BIGINT NOT NULL REFERENCES org(id) ON DELETE RESTRICT,
    provider VARCHAR(32) NOT NULL,
    external_account_id VARCHAR(128),
    display_name VARCHAR(128) NOT NULL DEFAULT '',
    credentials_enc TEXT,
    webhook_secret_enc TEXT,
    status VARCHAR(32) NOT NULL DEFAULT 'active',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT chk_git_connection_status CHECK (status IN ('active', 'disabled'))
);
CREATE INDEX idx_git_connection_org ON git_connection (org_id);

-- ── 4. 项目：org / slug / 可见性 / owner / 归档 ────────────────────────────
ALTER TABLE project ADD COLUMN org_id BIGINT;
ALTER TABLE project ADD COLUMN slug VARCHAR(64);
ALTER TABLE project ADD COLUMN description VARCHAR(1024) NOT NULL DEFAULT '';
ALTER TABLE project ADD COLUMN visibility VARCHAR(16) NOT NULL DEFAULT 'private';
ALTER TABLE project ADD COLUMN owner_id BIGINT;
ALTER TABLE project ADD COLUMN archived BOOLEAN NOT NULL DEFAULT FALSE;

UPDATE project
SET org_id = (SELECT id FROM org WHERE slug = 'default'),
    slug = CASE WHEN name = 'default' THEN 'default' ELSE 'project-' || id END,
    owner_id = COALESCE(owner_id, (SELECT id FROM app_user WHERE is_platform_admin ORDER BY id LIMIT 1))
WHERE org_id IS NULL OR slug IS NULL;

ALTER TABLE project DROP CONSTRAINT uk_project_name;
ALTER TABLE project ADD CONSTRAINT uk_project_org_slug UNIQUE (org_id, slug);
ALTER TABLE project ADD CONSTRAINT fk_project_org FOREIGN KEY (org_id) REFERENCES org(id) ON DELETE RESTRICT;
ALTER TABLE project ADD CONSTRAINT fk_project_owner FOREIGN KEY (owner_id) REFERENCES app_user(id) ON DELETE RESTRICT;
ALTER TABLE project ADD CONSTRAINT chk_project_visibility CHECK (visibility IN ('private', 'internal', 'public'));
CREATE INDEX idx_project_org ON project (org_id);

-- ── 5. 仓库：org / connection / external id ────────────────────────────────
ALTER TABLE repo ADD COLUMN org_id BIGINT;
ALTER TABLE repo ADD COLUMN connection_id BIGINT;
ALTER TABLE repo ADD COLUMN external_repo_id VARCHAR(128);

UPDATE repo r
SET org_id = p.org_id,
    external_repo_id = md5(r.url)
FROM project p
WHERE r.project_id = p.id
  AND (r.org_id IS NULL OR r.external_repo_id IS NULL);

ALTER TABLE repo ADD CONSTRAINT fk_repo_org FOREIGN KEY (org_id) REFERENCES org(id) ON DELETE RESTRICT;
ALTER TABLE repo ADD CONSTRAINT fk_repo_connection FOREIGN KEY (connection_id) REFERENCES git_connection(id) ON DELETE RESTRICT;
CREATE INDEX idx_repo_org ON repo (org_id);

-- ── 6. 真源绑定：单主约束 + 现有仓库回填一条 active ────────────────────────
CREATE TABLE repo_binding (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id BIGINT NOT NULL REFERENCES repo(id) ON DELETE RESTRICT,
    kind VARCHAR(32) NOT NULL,
    connection_id BIGINT REFERENCES git_connection(id) ON DELETE RESTRICT,
    external_repo_id VARCHAR(128),
    remote_url VARCHAR(512) NOT NULL,
    branch VARCHAR(128) NOT NULL DEFAULT 'main',
    status VARCHAR(32) NOT NULL DEFAULT 'candidate',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    retired_at TIMESTAMPTZ,
    CONSTRAINT chk_repo_binding_kind CHECK (kind IN ('managed', 'external')),
    CONSTRAINT chk_repo_binding_status CHECK (status IN ('candidate', 'active', 'retired'))
);
-- 同一逻辑仓库同一时刻至多一条 active（§4.4）
CREATE UNIQUE INDEX uk_repo_binding_active ON repo_binding (repo_id) WHERE status = 'active';
CREATE INDEX idx_repo_binding_repo ON repo_binding (repo_id);

INSERT INTO repo_binding (repo_id, kind, connection_id, external_repo_id, remote_url, branch, status, created_at)
SELECT r.id, 'managed', NULL, r.external_repo_id, r.url, r.branch, 'active', r.created_at
FROM repo r;

-- ── 7. membership 补 project 外键（project 已在管理库）────────────────────
ALTER TABLE membership ADD CONSTRAINT fk_membership_project FOREIGN KEY (project_id) REFERENCES project(id) ON DELETE RESTRICT;

-- ── 8. 租户冗余列 ──────────────────────────────────────────────────────────
ALTER TABLE comment ADD COLUMN org_id BIGINT;
ALTER TABLE subscription ADD COLUMN org_id BIGINT;
ALTER TABLE notification ADD COLUMN org_id BIGINT;
ALTER TABLE review ADD COLUMN org_id BIGINT;
ALTER TABLE mock_rule ADD COLUMN org_id BIGINT;
ALTER TABLE changelog ADD COLUMN org_id BIGINT;
ALTER TABLE release_marker ADD COLUMN org_id BIGINT;

UPDATE comment c SET org_id = r.org_id FROM repo r WHERE c.repo_id = r.id AND c.org_id IS NULL;
UPDATE subscription s SET org_id = r.org_id FROM repo r WHERE s.repo_id = r.id AND s.org_id IS NULL;
UPDATE notification n SET org_id = r.org_id FROM repo r WHERE n.repo_id = r.id AND n.org_id IS NULL;
UPDATE review v SET org_id = r.org_id FROM repo r WHERE v.repo_id = r.id AND v.org_id IS NULL;
UPDATE mock_rule m SET org_id = r.org_id FROM repo r WHERE m.repo_id = r.id AND m.org_id IS NULL;
UPDATE release_marker rm SET org_id = r.org_id FROM repo r WHERE rm.repo_id = r.id AND rm.org_id IS NULL;
UPDATE changelog SET org_id = (SELECT id FROM org WHERE slug = 'default') WHERE org_id IS NULL;

