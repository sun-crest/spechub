-- Phase B（B2）：团队绑定收紧
--
-- 前提：B2 写入路径已上线（SubscriptionService 总是写 team_id）。
-- 1. team_member 增加代理主键（Spring Data JDBC 单列 @Id），原复合键改为唯一键；
-- 2. 回填 B1→B2 窗口内旧代码写入的 subscription.team_id（按 team 文本查/建团队）；
-- 3. 同名合并产生的重复订阅去重（保留 id 最大）；
-- 4. 唯一键切换为 (repo_id, method, path, team_id)，team_id SET NOT NULL，旧 team 列改可空。

-- ── 1. team_member 代理主键 ────────────────────────────────────────────────
ALTER TABLE team_member DROP CONSTRAINT team_member_pkey;
ALTER TABLE team_member ADD COLUMN id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;
ALTER TABLE team_member ADD CONSTRAINT uk_team_member_team_user UNIQUE (team_id, user_id);

-- ── 2. 回填过渡期新增的 NULL team_id ─────────────────────────────────────
UPDATE subscription s
SET team_id = t.id
FROM team t
WHERE s.team_id IS NULL
  AND t.org_id = COALESCE(s.org_id, (SELECT r.org_id FROM repo r WHERE r.id = s.repo_id))
  AND LOWER(t.name) = LOWER(TRIM(s.team));

INSERT INTO team (org_id, name, description, created_at)
SELECT x.org_id, x.name, '', x.created_at
FROM (
    SELECT COALESCE(s.org_id, r.org_id) AS org_id,
           MIN(TRIM(s.team)) AS name,
           MIN(s.created_at) AS created_at
    FROM subscription s
    LEFT JOIN repo r ON r.id = s.repo_id
    WHERE s.team_id IS NULL
      AND COALESCE(s.org_id, r.org_id) IS NOT NULL
    GROUP BY COALESCE(s.org_id, r.org_id), LOWER(TRIM(s.team))
) x
WHERE NOT EXISTS (
    SELECT 1 FROM team t
    WHERE t.org_id = x.org_id AND LOWER(t.name) = LOWER(x.name)
);

UPDATE subscription s
SET team_id = t.id
FROM team t
WHERE s.team_id IS NULL
  AND t.org_id = COALESCE(s.org_id, (SELECT r.org_id FROM repo r WHERE r.id = s.repo_id))
  AND LOWER(t.name) = LOWER(TRIM(s.team));

-- B1→B2 窗口内旧代码写入的通知同样按团队名回填（匹配不到保留 NULL）。
UPDATE notification n
SET team_id = t.id
FROM team t
WHERE n.team_id IS NULL
  AND t.org_id = COALESCE(n.org_id, (SELECT r.org_id FROM repo r WHERE r.id = n.repo_id))
  AND LOWER(t.name) = LOWER(TRIM(n.team));

-- ── 3. 同名合并后的重复订阅去重（保留 id 最大的一条）──────────────────────
DELETE FROM subscription s
USING subscription d
WHERE s.repo_id = d.repo_id
  AND s.method = d.method
  AND s.path = d.path
  AND s.team_id = d.team_id
  AND s.id < d.id;

-- ── 4. 约束收紧 ────────────────────────────────────────────────────────────
-- 仍有 NULL（空团队名 / 无法确定 org）时在此失败，需先修复数据。
ALTER TABLE subscription ALTER COLUMN team_id SET NOT NULL;
ALTER TABLE subscription DROP CONSTRAINT uk_subscription_endpoint;
ALTER TABLE subscription ADD CONSTRAINT uk_subscription_team_endpoint UNIQUE (repo_id, method, path, team_id);
ALTER TABLE subscription ALTER COLUMN team DROP NOT NULL;
